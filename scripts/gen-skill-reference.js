#!/usr/bin/env node
// Regenerate skills/hey-axi/references/commands.md from src/manifest.json and src/policy.js.
//
//   npm run skill:reference
//
// test/skill.test.js fails when the committed file drifts from what this script renders,
// so run it after `npm run refresh-manifest` or a policy change.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadBundledManifest, listCommands } from "../src/router.js";
import { checkPolicy, runMode, sendStaging } from "../src/policy.js";

export const REFERENCE_PATH = fileURLToPath(new URL("../skills/hey-axi/references/commands.md", import.meta.url));

function note(path) {
  const none = new Set();
  const env = {};
  const tty = { stdin: true, stdout: true };
  if (sendStaging(path, none, env)) return "saved as a draft unless `--allow-send`";
  const refusal = checkPolicy(path, none, env, tty);
  if (refusal?.error === "send blocked") return "refused unless `--allow-send`";
  if (refusal?.error === "secret output blocked") return "refused unless `--allow-secret`";
  const mode = runMode(path, none);
  if (mode === "interactive") return path === "tui" ? "interactive, needs a TTY (user runs it)" : "interactive (user runs it)";
  if (mode === "stream") return "streams NDJSON";
  if (mode === "raw") return path === "timetrack export" ? "raw CSV unless `--output <file>`" : "raw output";
  return "";
}

const esc = (text) => String(text).replace(/\|/g, "\\|");

export function renderReference(manifest = loadBundledManifest()) {
  const commands = listCommands(manifest.commands);
  const groups = new Map();
  for (const node of commands) {
    const top = node.path.split(" ")[0];
    if (!groups.has(top)) groups.set(top, []);
    groups.get(top).push(node);
  }
  const lines = [
    "# hey-axi command reference",
    "",
    `<!-- Generated by scripts/gen-skill-reference.js from src/manifest.json (hey ${manifest.hey_version}). Do not edit by hand. -->`,
    "",
    `Every command from HEY CLI ${manifest.hey_version} (${commands.length} runnable paths, including the \`login\`/\`logout\` aliases and shortcut forms such as \`box <name>\`). Run each as \`hey-axi <command> [args] [flags]\`.`,
    "`hey-axi <command> --help` lists the flags offline, and `hey <command> --help` gives HEY's full explanation and argument names.",
    "Global flags that work with any command: `--account <id|all>`, `--json`, `--quiet`, `--ids-only`, `--count`, `--markdown`, `--html`, `--styled`, `--jq <expr>`.",
    "",
    "| Command | What it does | Flags | hey-axi behavior |",
    "|---|---|---|---|",
  ];
  for (const [, nodes] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    for (const node of nodes) {
      const flags = (node.flags || []).map((flag) => `\`--${flag.name}${flag.value ? " <v>" : ""}\``).join(" ");
      lines.push(`| \`${node.path}\` | ${esc(node.short)} | ${flags} | ${note(node.path)} |`);
    }
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(REFERENCE_PATH, renderReference());
  console.log(`wrote ${REFERENCE_PATH}`);
}
